    /**
     * @OA\Post(
     *      path="/api/download-content-types",
     *      operationId="storeDownloadContentType",
     *      tags={"7. E-Learning & Content - DownloadContentType"},
     *      summary="Store new download content type",
     *      description="Returns saved download content type data",
     *      security={{"sanctum":{}}},
     *      @OA\RequestBody(
     *          required=true,
     *          @OA\JsonContent(
