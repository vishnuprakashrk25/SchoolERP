    {
        $validator = Validator::make($request->all(), [
            'name' => 'required'
        ]);

        if ($validator->fails()) {
            return response()->json([
                'success' => false,
                'errors' => $validator->errors()
            ], 422);
        }

        $item = DownloadContentType::create($request->all());
        return response()->json([
            'success' => true,
            'data' => $item
        ]);
    }

