        public function update(Request $request, $id)
    {
        $item = FeeStructure::findOrFail($id);
        
        $validator = \Illuminate\Support\Facades\Validator::make($request->all(), [
            'class_id' => 'required|integer',
            'fee_type_id' => 'required|integer',
